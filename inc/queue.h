#ifndef QUEUE_H
#define QUEUE_H

#include <pthread.h>
#include <stddef.h>

/*
 * Потокобезопасная очередь общего назначения (producer/consumer).
 *
 * Хранит void* — очередь ничего не знает о том, что за ней стоит:
 * воркеры кладут в неё Conn_t* (задачи на обработку событий), а
 * агрегатор — Msg_t* (сообщения от источников). Очередь НЕ копирует
 * данные и не владеет ими — владение переходит от producer к consumer.
 */

typedef struct QNode_t QNode_t;

typedef struct Queue_t
{
    QNode_t *head;
    QNode_t *tail;
    size_t   size;

    pthread_mutex_t mutex;
    pthread_cond_t  cond;
    int shutdown;

    int notifyFd; /* -1, если не включено — см. queueEnableNotify() */
} Queue_t;

/* Создать пустую очередь. Возвращает NULL при ошибке. */
Queue_t *createQueue(void);

/*
 * Включает уведомление через eventfd в дополнение к pthread_cond: каждый
 * push() будет ещё и писать в notifyFd. Нужен потоку, который ждёт эту
 * очередь через epoll вместе с другими fd (сокет, shutdown), а не через
 * блокирующий pop() — так агрегатор мультиплексирует "новое сообщение" и
 * "сокет sink'а готов" одним epoll_wait(). Вызывать сразу после createQueue(),
 * до того как очередь станет видна другим потокам. Возвращает fd для
 * добавления в чужой epoll (EPOLLIN, уровень — счётчик eventfd только
 * накапливается, поэтому даже необработанное пробуждение не теряется),
 * либо -1 при ошибке.
 */
int queueEnableNotify(Queue_t *q);

/* Уничтожить очередь. Остаток элементов освобождается через freeItem
 * (если не NULL) — иначе просто отбрасывается (как раньше). */
void deleteQueue(Queue_t *q);
void deleteQueueWith(Queue_t *q, void (*freeItem)(void *item));

/*
 * Добавить элемент в конец очереди. Не блокируется, всегда успешен,
 * пока хватает памяти на служебный узел. Возвращает 0 при успехе, -1 при ошибке.
 */
int push(Queue_t *q, void *item);

/*
 * Извлечь элемент из начала очереди. БЛОКИРУЕТСЯ, если очередь пуста
 * (ждёт push() или shutdown). Возвращает 0 при успехе, -1 при shutdown/ошибке.
 */
int pop(Queue_t *q, void **item);

/*
 * Извлечь элемент, не блокируясь. Возвращает 0 при успехе, -1 если очередь
 * пуста (shutdown это не отличает от "пусто прямо сейчас" — вызывающий уже
 * знает о shutdown из своего собственного флага/сигнала).
 */
int trypop(Queue_t *q, void **item);

/* Текущее число элементов (под мьютексом — для водяных знаков backpressure). */
size_t queueSize(Queue_t *q);

/*
 * Сигнал завершения — разбудить все ожидающие потоки (и через notifyFd,
 * если он включён — иначе поток, ждущий очередь через epoll, не заметит
 * shutdown на пустой очереди никогда).
 * После вызова pop()/trypop() вернут -1, когда очередь опустеет.
 */
void shutdownQueue(Queue_t *q);

/*
 * true, если shutdownQueue() уже вызывался. Нужен потребителю на epoll+trypop(),
 * чтобы отличить "очередь опустела, но данные ещё могут прийти" от
 * "очередь опустела И больше никогда ничего не придёт" — только во втором
 * случае можно завершать поток.
 */
int queueIsShutdown(Queue_t *q);

#endif /* QUEUE_H */
